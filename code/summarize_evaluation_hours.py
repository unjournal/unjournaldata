#!/usr/bin/env python3
"""Build the blog's aggregate hours summary from the approved public export."""
import argparse
import csv
import hashlib
import json
import math
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--as-of", required=True, help="Date this export was checked (YYYY-MM-DD)")
    args = parser.parse_args()
    from datetime import date
    date.fromisoformat(args.as_of)
    source = ROOT / "data/evaluator_paper_level.csv"
    manifest = json.loads((ROOT / "data/public_export_manifest.json").read_text())
    expected = manifest["files"][source.name]
    if hashlib.sha256(source.read_bytes()).hexdigest() != expected["sha256"]:
        raise ValueError("Hours export does not match its public manifest")
    with source.open(newline="") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != ["evaluation_stream", "hours_spent_manual_impute"]:
            raise ValueError("Unexpected public hours schema")
        rows = list(reader)
    if len(rows) != expected["rows"]:
        raise ValueError("Hours export row count does not match manifest")
    hours = [float(row["hours_spent_manual_impute"]) for row in rows
             if row["hours_spent_manual_impute"].strip()]
    if len(hours) < 2 or any(not math.isfinite(x) or x < 0 for x in hours):
        raise ValueError("Need at least two finite, nonnegative hours values")
    q1, _, q3 = statistics.quantiles(hours, method="inclusive")
    n, total = len(hours), len(rows)
    text = f"""<!-- Generated by code/summarize_evaluation_hours.py; do not edit manually. -->
**Evaluators reported a median of {statistics.median(hours):g} hours per evaluation and a mean of {statistics.mean(hours):.1f} hours**, across {n} evaluation records with a usable hours value. The middle half took {q1:g}–{q3:g} hours; the full range was {min(hours):g}–{max(hours):g} hours.

| Measure | Hours |
|:--|--:|
| Median | {statistics.median(hours):g} |
| Mean | {statistics.mean(hours):.1f} |
| 25th percentile | {q1:g} |
| 75th percentile | {q3:g} |
| Minimum | {min(hours):g} |
| Maximum | {max(hours):g} |

The public export contains {total} evaluation records: {n} ({100*n/total:.1f}%) have a usable hours value and {total-n} do not. These statistics describe the records with reported hours. They may not represent evaluations without reported hours, and multiple records may come from the same evaluator.

*Public export checked {args.as_of}. This is the date of this calculation, not a claim that the underlying survey responses are recent.*
"""
    output = ROOT / "website/posts/evaluator-survey-insights/_hours-summary.md"
    output.write_text(text)
    print(f"Wrote {output.relative_to(ROOT)} ({n}/{total} records with hours)")


if __name__ == "__main__":
    main()
