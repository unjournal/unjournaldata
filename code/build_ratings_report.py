#!/usr/bin/env python3
"""Assemble the ratings report: substitute {{tbl_*}} placeholders with markdown tables,
write report.md, and render a self-contained HTML page (figures as separate files)."""
import re
import sys
from pathlib import Path

import markdown

template = Path(sys.argv[1]).read_text(encoding="utf-8")
md_dir = Path(sys.argv[2])
out_md = Path(sys.argv[3])
out_html = Path(sys.argv[4])


def sub(m):
    p = md_dir / (m.group(1) + ".md")
    return p.read_text(encoding="utf-8") if p.exists() else f"*(table {m.group(1)} missing)*"


text = re.sub(r"\{\{(tbl_[a-z0-9_]+)\}\}", sub, template)
out_md.write_text(text, encoding="utf-8")

if len(sys.argv) > 5:
    # Quarto draft post: YAML header, tables pulled in with include shortcodes so a re-run of the
    # analysis script refreshes every table and figure without editing prose.
    qmd_body = re.sub(r"\{\{(tbl_[a-z0-9_]+)\}\}", lambda m: "{{< include results/md/" + m.group(1) + ".md >}}", template)
    qmd_body = qmd_body.split("\n", 1)[1]  # drop the H1; the YAML title replaces it
    header = """---
title: "Ratings, intervals, reliability and calibration: a 2026 reanalysis"
author: "David Reinstein with Claude Code assistance"
date: "2026-10-16"
draft: true
categories: [data, analysis, evaluators]
description: "What 114 evaluations of 61 papers say about how evaluators use the percentile scales and 90% intervals, how much they agree, and what to change in the form."
---

::: callout-warning
## Draft
Generated by `code/analyze_ratings_quality.py`; tables and figures under `results/` are its outputs. Prose was drafted with Claude Code and has not yet been reviewed. Remove `draft: true` to publish.
:::
"""
    Path(sys.argv[5]).write_text(header + qmd_body, encoding="utf-8")

body = markdown.markdown(text, extensions=["tables", "fenced_code"])
body = body.replace('src="results/', 'src="')

css = """
<title>Unjournal Ratings Reanalysis</title>
<style>
/* layout: single reading column, tables scroll in their own box */
:root{--bg:#fbfaf7;--fg:#1f2328;--muted:#5b6066;--accent:#1f5f8b;--rule:#d9d5cc;--tbl:#f1efe9;--code:#edeae2;
 --font-body:Georgia,"Iowan Old Style","Times New Roman",serif;--font-ui:"Helvetica Neue",Arial,sans-serif;--font-mono:Menlo,Consolas,monospace}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){--bg:#15181c;--fg:#e6e3dc;--muted:#a9ada7;--accent:#7fb3d8;--rule:#3a3f45;--tbl:#1e2228;--code:#23272e;color-scheme:dark}}
:root[data-theme="dark"]{--bg:#15181c;--fg:#e6e3dc;--muted:#a9ada7;--accent:#7fb3d8;--rule:#3a3f45;--tbl:#1e2228;--code:#23272e;color-scheme:dark}
body{background:var(--bg);color:var(--fg);font-family:var(--font-body);font-size:16px;line-height:1.55;padding-block:24px;padding-inline:16px}
main{max-width:46rem;margin:0 auto;min-width:0}
h1{font-family:var(--font-ui);font-size:1.7rem;line-height:1.2;text-wrap:balance;letter-spacing:-0.01em;margin:0 0 1rem}
h2{font-family:var(--font-ui);font-size:1.25rem;margin:2.2rem 0 .6rem;border-bottom:1px solid var(--rule);padding-bottom:.3rem}
h3{font-family:var(--font-ui);font-size:1.05rem;margin:1.5rem 0 .5rem}
p{margin:.7rem 0;max-width:65ch}
li{margin:.3rem 0}
em{color:var(--muted)}
a{color:var(--accent)}
img{max-width:100%;height:auto;display:block;margin:1rem 0;border:1px solid var(--rule);background:#fff}
.tbl{overflow-x:auto;margin:1rem 0;border:1px solid var(--rule);border-radius:4px}
table{border-collapse:collapse;font-family:var(--font-ui);font-size:.82rem;font-variant-numeric:tabular-nums;min-width:100%}
th,td{padding:.35rem .55rem;border-bottom:1px solid var(--rule);text-align:left;white-space:nowrap}
th{background:var(--tbl);font-weight:600}
pre{background:var(--code);padding:.8rem;overflow-x:auto;font-family:var(--font-mono);font-size:.8rem;border-radius:4px}
code{font-family:var(--font-mono);font-size:.88em}
ol,ul{padding-left:1.4rem}
</style>
"""
body = re.sub(r"<table>", '<div class="tbl"><table>', body)
body = body.replace("</table>", "</table></div>")
out_html.write_text(css + "<main>" + body + "</main>", encoding="utf-8")
print("wrote", out_md, out_html, len(out_html.read_text(encoding='utf-8')))
